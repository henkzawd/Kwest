export const dict = { no, en };

export let lang = (() => {
  try { return localStorage.getItem('kwest-lang') === 'en' ? 'en' : 'no'; } catch { return 'no'; }
})();

export function t(key, vars) {
  let s = dict[lang][key] ?? dict.no[key];
  if (s === undefined) { console.warn('Mangler tekst:', key); s = key; }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}

export function setLang(l) {
  lang = l;
  try { localStorage.setItem('kwest-lang', l); } catch { /* ignorer */ }
  document.documentElement.lang = l === 'en' ? 'en' : 'nb';
}

export function langButton(onChange) {
  return h('button', {
    class: 'lang-btn', type: 'button',
    onclick: () => { setLang(lang === 'en' ? 'no' : 'en'); onChange(); },
  }, t('lang.switch'));
}

